"""Prepare the repository UI font at development time; no font conversion runs during gameplay."""

import argparse
import shutil
from pathlib import Path

from fontTools.ttLib import TTFont

# Latin, Latin-1, Latin Extended-A and general punctuation: the game's text is English and Latin-script.
RANGES = [(32, 126), (160, 383), (8192, 8303)]
# The bake's size in points (the pipeline rasterizes at 96 dpi): twice the reference's 14-pixel text, drawn at half
# scale (HudPainter.TextScale), so the text stays sharp at an interface scale of two.
BAKE_POINTS = 21


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("font", type=Path, help="DejaVuSans.ttf")
    parser.add_argument("license", type=Path, help="the DejaVu fonts' LICENSE")
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    destination = root / "assets/Hud/Fonts"
    destination.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(arguments.font, destination / "DejaVuSans.ttf")
    shutil.copyfile(arguments.license, destination / "DejaVu-LICENSE.txt")

    cmap = TTFont(arguments.font).getBestCmap()
    supported = sorted(value for start, end in RANGES for value in range(start, end + 1) if value in cmap)
    regions = []
    for value in supported:
        if regions and value == regions[-1][1] + 1:
            regions[-1][1] = value
        else:
            regions.append([value, value])
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by tools/ui/build_font.py; baked glyphs avoid runtime font rasterization. -->',
        '<XnaContent xmlns:Graphics="Microsoft.Xna.Framework.Content.Pipeline.Graphics">',
        '  <Asset Type="Graphics:FontDescription">',
        '    <FontName>../../../../assets/Hud/Fonts/DejaVuSans.ttf</FontName>',
        f'    <Size>{BAKE_POINTS}</Size>',
        '    <Spacing>0</Spacing>',
        '    <UseKerning>true</UseKerning>',
        '    <Style>Regular</Style>',
        '    <DefaultCharacter>?</DefaultCharacter>',
        '    <CharacterRegions>',
    ]
    for start, end in regions:
        lines.extend([
            '      <CharacterRegion>',
            f'        <Start>&#{start};</Start>',
            f'        <End>&#{end};</End>',
            '      </CharacterRegion>',
        ])
    lines.extend(['    </CharacterRegions>', '  </Asset>', '</XnaContent>', ''])
    with open(root / 'Client/PristonTale/Content/Fonts/UI.spritefont', 'w', encoding='utf-8', newline='\n') as output:
        output.write('\n'.join(lines))


if __name__ == "__main__":
    main()
